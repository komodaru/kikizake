//! BC6H and BC7 (BPTC) block decoding, as the Direct3D 11 format pages give it ("BC6H Format",
//! "BC7 Format"): the modes, endpoints, partitions and weights.

struct Bits(u128);

impl Bits {
    fn take(&mut self, n: u8) -> u32 {
        let v = (self.0 & ((1u128 << n) - 1)) as u32;
        self.0 >>= n;
        v
    }
    /// (BC6H's fields stored with their bits reversed)
    fn take_rev(&mut self, n: u8) -> u32 {
        let v = self.take(n);
        (0..n).fold(0, |a, i| a << 1 | (v >> i & 1))
    }
}

fn sext(v: i32, bits: u32) -> i32 {
    (v << (32 - bits)) >> (32 - bits)
}

fn lerp(a: i32, b: i32, w: &[i32], i: usize) -> i32 {
    (a * (64 - w[i]) + b * w[i] + 32) >> 6
}

const W2: [i32; 4] = [0, 21, 43, 64];
const W3: [i32; 8] = [0, 9, 18, 27, 37, 46, 55, 64];
const W4: [i32; 16] = [0, 4, 9, 13, 17, 21, 26, 30, 34, 38, 43, 47, 51, 55, 60, 64];

/// the BC6H texel (x, y) of a block: the three channels as 16-bit floats; a reserved mode gives
/// zeros
pub fn bc6h(b: &[u8; 16], signed: bool, x: u32, y: u32) -> [u16; 3] {
    // (the endpoint precision of each mode, then the delta precisions of r, g, b)
    const BITS: [[u32; 14]; 4] = [
        [10, 7, 11, 11, 11, 9, 8, 8, 8, 6, 10, 11, 12, 16],
        [5, 6, 5, 4, 4, 5, 6, 5, 5, 6, 10, 9, 8, 4],
        [5, 6, 4, 5, 4, 5, 5, 6, 5, 6, 10, 9, 8, 4],
        [5, 6, 4, 4, 5, 5, 5, 5, 6, 6, 10, 9, 8, 4],
    ];
    let mut s = Bits(u128::from_le_bytes(*b));
    let mut m = s.take(2);
    if m > 1 {
        m |= s.take(3) << 2;
    }
    let Some(mode) = BC6H_MODES.iter().position(|(bits, _)| *bits == m) else { return [0; 3] };
    let mut e = [0i32; 13];
    for &(t, n, sh, rev) in BC6H_MODES[mode].1 {
        let v = if rev == 1 { s.take_rev(n) } else { s.take(n) };
        e[t as usize] |= (v << sh) as i32;
    }
    let part = e[12] as usize;
    let one = mode >= 10;
    let n = if one { 2 } else { 4 };
    let p = BITS[0][mode];
    for c in 0..3 {
        let ch = &mut e[c * 4..c * 4 + 4];
        if signed {
            ch[0] = sext(ch[0], p);
        }
        if !(mode == 9 || mode == 10) || signed {
            for v in ch.iter_mut().take(n).skip(1) {
                *v = sext(*v, BITS[c + 1][mode]);
            }
        }
        if !(mode == 9 || mode == 10) {
            for i in 1..n {
                ch[i] = (ch[i] + ch[0]) & ((1 << p) - 1);
                if signed {
                    ch[i] = sext(ch[i], p);
                }
            }
        }
        for v in ch.iter_mut().take(n) {
            *v = unquantize(*v, p, signed);
        }
    }
    // (the indices: 3 bits, 4 with one region; an anchor's one less)
    let at = (y * 4 + x) as usize;
    let mut idx = 0;
    let mut set = 0;
    for i in 0..=at {
        let ps = if one { if i == 0 { 128 } else { 0 } } else { PART2[part][i] };
        let bits = if one { 4 } else { 3 } - (ps >> 7);
        let v = s.take(bits) as usize;
        if i == at {
            idx = v;
            set = (ps & 1) as usize;
        }
    }
    let w: &[i32] = if one { &W4 } else { &W3 };
    [0, 1, 2].map(|c| finish(lerp(e[c * 4 + set * 2], e[c * 4 + set * 2 + 1], w, idx), signed))
}

fn unquantize(v: i32, bits: u32, signed: bool) -> i32 {
    if !signed {
        if bits >= 15 {
            v
        } else if v == 0 {
            0
        } else if v == (1 << bits) - 1 {
            0xffff
        } else {
            ((v << 16) + 0x8000) >> bits
        }
    } else if bits >= 16 {
        v
    } else {
        let (neg, a) = (v < 0, v.abs());
        let u = if a == 0 {
            0
        } else if a >= (1 << (bits - 1)) - 1 {
            0x7fff
        } else {
            ((a << 15) + 0x4000) >> (bits - 1)
        };
        if neg { -u } else { u }
    }
}

fn finish(v: i32, signed: bool) -> u16 {
    if !signed {
        ((v * 31) >> 6) as u16
    } else {
        let a = (v.abs() * 31) >> 5;
        if v < 0 { 0x8000 | a as u16 } else { a as u16 }
    }
}

/// the BC7 texel (x, y) of a block, RGBA8; a reserved mode gives zeros
pub fn bc7(b: &[u8; 16], x: u32, y: u32) -> [u8; 4] {
    const RGB: [u32; 8] = [4, 6, 5, 7, 5, 7, 7, 5];
    const ALPHA: [u32; 8] = [0, 0, 0, 0, 6, 8, 7, 5];
    const PBITS: u32 = 0b1100_1011;
    let mut s = Bits(u128::from_le_bytes(*b));
    let Some(mode) = (0..8).find(|_| s.take(1) == 1) else { return [0; 4] };
    let (mut parts, mut part, mut rot, mut isel) = (1, 0, 0, 0);
    if [0, 1, 2, 3, 7].contains(&mode) {
        parts = if mode == 0 || mode == 2 { 3 } else { 2 };
        part = s.take(if mode == 0 { 4 } else { 6 }) as usize;
    }
    if mode == 4 || mode == 5 {
        rot = s.take(2);
        if mode == 4 {
            isel = s.take(1);
        }
    }
    let ne = parts * 2;
    let mut e = [[0u32; 4]; 6];
    for c in 0..3 {
        for ep in e.iter_mut().take(ne) {
            ep[c] = s.take(RGB[mode] as u8);
        }
    }
    if ALPHA[mode] > 0 {
        for ep in e.iter_mut().take(ne) {
            ep[3] = s.take(ALPHA[mode] as u8);
        }
    }
    let pb = PBITS >> mode & 1;
    if [0, 1, 3, 6, 7].contains(&mode) {
        for ep in e.iter_mut().take(ne) {
            for c in ep.iter_mut() {
                *c <<= 1;
            }
        }
        if mode == 1 {
            let (i, j) = (s.take(1), s.take(1));
            for c in 0..3 {
                e[0][c] |= i;
                e[1][c] |= i;
                e[2][c] |= j;
                e[3][c] |= j;
            }
        } else {
            for ep in e.iter_mut().take(ne) {
                let j = s.take(1);
                for c in ep.iter_mut() {
                    *c |= j;
                }
            }
        }
    }
    for ep in e.iter_mut().take(ne) {
        let j = RGB[mode] + pb;
        for c in ep.iter_mut().take(3) {
            *c <<= 8 - j;
            *c |= *c >> j;
        }
        let j = ALPHA[mode] + pb;
        ep[3] <<= 8 - j;
        ep[3] |= ep[3] >> j;
        if ALPHA[mode] == 0 {
            ep[3] = 0xff;
        }
    }
    let set_of = |i: usize| -> u8 {
        match parts {
            1 => if i == 0 { 128 } else { 0 },
            2 => PART2[part][i],
            _ => PART3[part][i],
        }
    };
    let ib = if mode == 0 || mode == 1 { 3 } else if mode == 6 { 4 } else { 2 };
    let ib2 = if mode == 4 { 3 } else if mode == 5 { 2 } else { 0 };
    let at = (y * 4 + x) as usize;
    let mut idx = [0usize; 16];
    for (i, v) in idx.iter_mut().enumerate() {
        *v = s.take(ib - (set_of(i) >> 7)) as usize;
    }
    let mut idx2 = [0usize; 16];
    if ib2 > 0 {
        for (i, v) in idx2.iter_mut().enumerate() {
            *v = s.take(if i == 0 { ib2 - 1 } else { ib2 }) as usize;
        }
    }
    let w = |n: u8| -> &'static [i32] { match n { 2 => &W2, 3 => &W3, _ => &W4 } };
    let set = (set_of(at) & 3) as usize;
    let (a, z) = (e[set * 2].map(|v| v as i32), e[set * 2 + 1].map(|v| v as i32));
    let mut px = [0i32; 4];
    for c in 0..4 {
        let (wt, i) = if ib2 == 0 || (isel == 0) == (c < 3) { (w(ib), idx[at]) } else { (w(ib2), idx2[at]) };
        px[c] = lerp(a[c], z[c], wt, i);
    }
    match rot {
        1 => px.swap(3, 0),
        2 => px.swap(3, 1),
        3 => px.swap(3, 2),
        _ => {}
    }
    px.map(|v| v as u8)
}

