#!/usr/bin/env python3
"""src/model/d3dfmt_table.rs from Windows' answers: every `fmt` line of golden/d3d11res-64 and
golden/d3d10res-64 (CheckFormatSupport, FORMAT_SUPPORT2, the quality levels; WARP on
windows-2025), one table per device and feature level.

    python3 tools/d3dfmt.py > src/model/d3dfmt_table.rs
"""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
print("//! Generated by tools/d3dfmt.py from golden/d3d11res-64 and golden/d3d10res-64: what")
print("//! CheckFormatSupport, CheckFeatureSupport(FORMAT_SUPPORT2) and CheckMultisampleQualityLevels")
print("//! (2, 4, 8, 16 samples; 0x80070057: the call failed) answer for every format (measured: a table")
print("//! of every value Windows gave; WARP).")
print("/// (device line, [(format, hr, support, hr2, support2, quality levels)])")
print("pub type Row = (u32, u32, u32, u32, u32, [u32; 4]);")
print("pub const TABLES: &[(&str, &[Row])] = &[")
for suite in ["d3d11res", "d3d10res"]:
    cur = None
    for l in open(os.path.join(ROOT, "golden", suite + "-64", "stdout.txt")):
        t = l.split()
        if not t:
            continue
        if t[0] == "case" and t[1].startswith("fmt-"):
            cur = []
        elif t[0] in ("device11", "device10", "device10_1") and cur is not None and not cur and t[-1] == "ok":
            pass
        elif t[0] == "fmt" and cur is not None:
            q = [int(x[1:], 16) if x.startswith("x") else int(x) for x in t[7:11]]
            num = lambda x: 0 if x == "-" else int(x, 16)
            cur.append((int(t[1]), num(t[2]), num(t[3]), num(t[4]), num(t[5]), q))
        elif t[0] == "case" and cur is not None:
            cur = None
        if t[0] == "case" and t[1].startswith("fmt-"):
            name = suite + ":" + t[1]
            print('    ("%s", &[' % name)
        if cur is not None and t[0] == "fmt" and int(t[1]) == 0xffffffff:
            for r in cur:
                print("        (%#x, %#x, %#x, %#x, %#x, [%#x, %#x, %#x, %#x])," % (r[0], r[1], r[2], r[3], r[4], *r[5]))
            print("    ]),")
            cur = None
print("];")
